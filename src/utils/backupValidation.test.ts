test('rejects backups missing version or using unsupported version', () => {
  const noVersion = createValidV2Backup() as unknown as Record<string, unknown>;
  delete noVersion.version;
  const res1 = validateBackupJson(JSON.stringify(noVersion));
  assert.equal(res1.ok, false);
  if (!res1.ok) {
    assert.match(res1.error, /Missing required "version"/);
  }

  const badVersion = { ...createValidV2Backup(), version: 99 };
  const res2 = validateBackupJson(JSON.stringify(badVersion));
  assert.equal(res2.ok, false);
  if (!res2.ok) {
    assert.match(res2.error, /Unsupported backup version/);
  }
});

test('rejects v2 backups missing required sections (preferences, tasks, habit, academy)', () => {
  for (const requiredKey of ['preferences', 'tasks', 'records', 'habit', 'prayerConfig', 'prayerRecords', 'academy']) {
    const partial = createValidV2Backup() as unknown as Record<string, unknown>;
    delete partial[requiredKey];
    const res = validateBackupJson(JSON.stringify(partial));
    assert.equal(res.ok, false, `Expected missing ${requiredKey} to fail`);
    if (!res.ok) {
      assert.match(res.error, new RegExp(`Missing required backup section "${requiredKey}"`));
    }
  }
});

test('rejects items with missing nested required fields', () => {
  // Task missing title
  const badTaskBackup = createValidV2Backup();
  badTaskBackup.tasks = [{ id: 't1', timeSlot: '9:00 AM', category: 'morning', order: 1 } as never];
  const resTask = validateBackupJson(JSON.stringify(badTaskBackup));
  assert.equal(resTask.ok, false);
  if (!resTask.ok) {
    assert.match(resTask.error, /tasks\[0\]\.title/);
  }

  // Habit missing createdDate
  const badHabitBackup = createValidV2Backup() as unknown as Record<string, unknown>;
  badHabitBackup.habit = { habitName: 'Scroll', answers: {} };
  const resHabit = validateBackupJson(JSON.stringify(badHabitBackup));
  assert.equal(resHabit.ok, false);
  if (!resHabit.ok) {
    assert.match(resHabit.error, /habit\.createdDate/);
  }

  // PrayerConfig missing reminder key
  const badPrayerBackup = createValidV2Backup();
  const remindersCopy = { ...badPrayerBackup.prayerConfig.reminders } as Record<string, unknown>;
  delete remindersCopy.fajr;
  badPrayerBackup.prayerConfig = {
    ...badPrayerBackup.prayerConfig,
    reminders: remindersCopy as never,
  };
  const resPrayer = validateBackupJson(JSON.stringify(badPrayerBackup));
  assert.equal(resPrayer.ok, false);
  if (!resPrayer.ok) {
    assert.match(resPrayer.error, /prayerConfig\.reminders\.fajr/);
  }
});

