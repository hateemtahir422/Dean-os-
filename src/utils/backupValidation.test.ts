// 3. Security & Unexpected Fields
// ---------------------------------------------------------------------------

test('rejects prototype pollution payloads (__proto__, constructor, prototype)', () => {
  const base = createValidV2Backup();
  const withProto = `{"__proto__": {"isAdmin": true}, ${JSON.stringify(base).slice(1)}`;
  const res1 = validateBackupJson(withProto);
  assert.equal(res1.ok, false);
  if (!res1.ok) {
    assert.match(res1.error, /unsafe property key/i);
  }

  const nestedUnsafe = JSON.stringify({
    ...base,
    preferences: { ...base.preferences, constructor: { evil: true } },
  });
  const res2 = validateBackupJson(nestedUnsafe);
  assert.equal(res2.ok, false);
  if (!res2.ok) {
    assert.match(res2.error, /unsafe property key/i);
  }
});

test('rejects unexpected top-level or nested properties', () => {
  const unrelatedJson = JSON.stringify({ name: 'other-app', dependencies: {} });
  const res1 = validateBackupJson(unrelatedJson);
  assert.equal(res1.ok, false);
  if (!res1.ok) {
    assert.match(res1.error, /Unexpected property/i);
  }

  const backup = createValidV2Backup() as unknown as Record<string, unknown>;
  backup.unexpectedField = true;
  const res2 = validateBackupJson(JSON.stringify(backup));
  assert.equal(res2.ok, false);
  if (!res2.ok) {
    assert.match(res2.error, /Unexpected property "unexpectedField"/);
  }
});

