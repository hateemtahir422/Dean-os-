import test from 'node:test';
import assert from 'node:assert/strict';
import { MAX_BACKUP_BYTES, ValidatedBackupPayload, validateBackupJson } from './backupValidation';
import { importBackupToStorage, STORAGE_KEYS, Storage, StorageLike } from './storage';
import { DEFAULT_ACADEMY_CONFIG, DEFAULT_ROUTINE_TASKS, INITIAL_PROJECTS, INITIAL_PROSPECTS } from './defaultData';
import { DEFAULT_PRAYER_CONFIG } from './prayer';

function createValidV2Backup(): ValidatedBackupPayload {
  return {
    version: 2,
    exportedAt: '2026-11-17T08:00:00.000Z',
    preferences: {
      userName: 'Alex',
      hasCompletedOnboarding: true,
      showPrayerTimes: true,
    },
    tasks: DEFAULT_ROUTINE_TASKS,
    records: {
      '2026-11-17': {
        date: '2026-11-17',
        completedTaskIds: ['task-morning-routine'],
        completedSubtaskIds: {
          'task-morning-routine': ['sub-wake', 'sub-water'],
        },
        notes: 'Calm start today.',
      },
    },
    habit: {
      habitName: 'Late Night Scrolling',
      createdDate: '2026-11-01',
      answers: {
        '2026-11-15': 'YES',
        '2026-11-16': 'NO',
        '2026-11-17': 'YES',
      },
    },
    prayerConfig: DEFAULT_PRAYER_CONFIG,
    prayerRecords: {
      '2026-11-17': {
        date: '2026-11-17',
        completedPrayers: {
          fajr: true,
          dhuhr: true,
          asr: false,
          maghrib: false,
          isha: false,
        },
      },
    },
    prospects: INITIAL_PROSPECTS,
    projects: INITIAL_PROJECTS,
    academy: DEFAULT_ACADEMY_CONFIG,
  };
}

function createMemoryStorage(initial: Record<string, string> = {}): StorageLike & { store: Map<string, string> } {
  const store = new Map<string, string>(Object.entries(initial));
  return {
    store,
    getItem(key: string) {
      return store.has(key) ? store.get(key)! : null;
    },
    setItem(key: string, value: string) {
      store.set(key, value);
    },
    removeItem(key: string) {
      store.delete(key);
    },
  };
}

// ---------------------------------------------------------------------------
// 1. Valid Backups (v2 current + v1 previous version compatibility)
// ---------------------------------------------------------------------------

test('accepts a valid v2 backup with full structure and populated records', () => {
  const backup = createValidV2Backup();
  const result = validateBackupJson(JSON.stringify(backup));

  assert.equal(result.ok, true);
  if (result.ok) {
    assert.equal(result.data.version, 2);
    assert.equal(result.data.preferences?.userName, 'Alex');
    assert.equal(result.data.tasks.length, DEFAULT_ROUTINE_TASKS.length);
    assert.equal(result.data.habit.answers['2026-11-17'], 'YES');
    assert.ok(result.importedSections.includes('preferences'));
    assert.ok(result.importedSections.includes('tasks'));
    assert.ok(result.importedSections.includes('academy'));
  }
});

test('accepts backup generated by Storage.exportFullBackup()', () => {
  const exported = Storage.exportFullBackup();
  const result = validateBackupJson(exported);
  assert.equal(result.ok, true);
});

test('preserves compatibility with valid v1 backups created before preferences existed', () => {
  const v1Backup = {
    version: 1,
    exportedAt: '2026-10-15T10:00:00.000Z',
    tasks: DEFAULT_ROUTINE_TASKS,
    records: {
      '2026-10-15': {
        date: '2026-10-15',
        completedTaskIds: ['task-morning-routine'],
      },
    },
    habit: {
      habitName: 'Doomscrolling',
      createdDate: '2026-10-01',
      answers: { '2026-10-15': 'YES' },
    },
    prayerConfig: DEFAULT_PRAYER_CONFIG,
    prayerRecords: {},
    academy: DEFAULT_ACADEMY_CONFIG,
  };

  const result = validateBackupJson(JSON.stringify(v1Backup));
  assert.equal(result.ok, true);
  if (result.ok) {
    assert.equal(result.data.version, 1);
    assert.equal(result.data.preferences, undefined);
    assert.deepEqual(result.data.records['2026-10-15'].completedSubtaskIds, {});
  }
});

test('accepts a v2 backup with UTF-8 BOM and omitted optional legacy prospects/projects', () => {
  const backup = createValidV2Backup() as unknown as Record<string, unknown>;
  delete backup.prospects;
  delete backup.projects;

  const result = validateBackupJson(`\uFEFF${JSON.stringify(backup)}`);
  assert.equal(result.ok, true);
});

