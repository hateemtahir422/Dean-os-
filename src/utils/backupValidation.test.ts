// 5. Incorrect Data Types & Invalid Domain Values
// ---------------------------------------------------------------------------

test('rejects incorrect data types across storage keys', () => {
  // tasks is a string instead of array
  const badTasksType = { ...createValidV2Backup(), tasks: 'corrupted-tasks' };
  const res1 = validateBackupJson(JSON.stringify(badTasksType));
  assert.equal(res1.ok, false);
  if (!res1.ok) assert.match(res1.error, /"tasks" section: expected an array/);

  // preferences.showPrayerTimes is a string instead of boolean
  const badPref = createValidV2Backup();
  badPref.preferences = { userName: 'Alex', hasCompletedOnboarding: true, showPrayerTimes: 'yes' as never };
  const res2 = validateBackupJson(JSON.stringify(badPref));
  assert.equal(res2.ok, false);
  if (!res2.ok) assert.match(res2.error, /preferences\.showPrayerTimes/);

  // task.order is a string instead of number
  const badOrder = createValidV2Backup();
  badOrder.tasks = [{ ...DEFAULT_ROUTINE_TASKS[0], order: '1' as never }];
  const res3 = validateBackupJson(JSON.stringify(badOrder));
  assert.equal(res3.ok, false);
  if (!res3.ok) assert.match(res3.error, /tasks\[0\]\.order/);

  // habit.answers has invalid answer value and invalid calendar date
  const badHabitVal = createValidV2Backup();
  badHabitVal.habit = { habitName: 'Scroll', createdDate: '2026-11-01', answers: { '2026-11-17': 'MAYBE' as never } };
  const res4 = validateBackupJson(JSON.stringify(badHabitVal));
  assert.equal(res4.ok, false);
  if (!res4.ok) assert.match(res4.error, /expected "YES" or "NO"/);

  const badCalendarDate = createValidV2Backup();
  badCalendarDate.habit = { habitName: 'Scroll', createdDate: '2026-02-30', answers: {} };
  const res5 = validateBackupJson(JSON.stringify(badCalendarDate));
  assert.equal(res5.ok, false);
  if (!res5.ok) assert.match(res5.error, /habit\.createdDate/);

  // records date mismatch
  const badRecordDate = createValidV2Backup();
  badRecordDate.records = {
    '2026-11-17': {
      date: '2026-11-18',
      completedTaskIds: [],
      completedSubtaskIds: {},
    },
  };
  const res6 = validateBackupJson(JSON.stringify(badRecordDate));
  assert.equal(res6.ok, false);
  if (!res6.ok) assert.match(res6.error, /must match record key/);

  // prayerConfig out-of-range latitude
  const badLat = createValidV2Backup();
  badLat.prayerConfig = { ...badLat.prayerConfig, latitude: 145 };
  const res7 = validateBackupJson(JSON.stringify(badLat));
  assert.equal(res7.ok, false);
  if (!res7.ok) assert.match(res7.error, /prayerConfig\.latitude/);

  // academy invalid day of week & time format
  const badAcademy = createValidV2Backup();
  badAcademy.academy = { ...badAcademy.academy, daysOfWeek: [1, 9] };
  const res8 = validateBackupJson(JSON.stringify(badAcademy));
  assert.equal(res8.ok, false);
  if (!res8.ok) assert.match(res8.error, /academy\.daysOfWeek/);

  // projects negative earnings
  const badProject = createValidV2Backup();
  badProject.projects = [{ ...INITIAL_PROJECTS[0], estimatedEarnings: -500 }];
  const res9 = validateBackupJson(JSON.stringify(badProject));
  assert.equal(res9.ok, false);
  if (!res9.ok) assert.match(res9.error, /estimatedEarnings/);
});

