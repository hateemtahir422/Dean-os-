test('importBackupToStorage never overwrites existing data when validation fails', () => {
  const existingPrefs = JSON.stringify({
    userName: 'ExistingUser',
    hasCompletedOnboarding: true,
    showPrayerTimes: false,
  });
  const existingTasks = JSON.stringify([{ id: 'keep-me', title: 'Keep Me', timeSlot: '8 AM', category: 'morning', order: 1 }]);
  const storage = createMemoryStorage({
    [STORAGE_KEYS.PREFERENCES]: existingPrefs,
    [STORAGE_KEYS.TASKS]: existingTasks,
  });

  // Validate non-overwrite with invalid habit
  const partiallyBroken = createValidV2Backup();
  partiallyBroken.preferences!.userName = 'ShouldNotOverwrite';
  partiallyBroken.habit = { habitName: 'Scroll', createdDate: 'bad-date', answers: {} };

  const result = importBackupToStorage(JSON.stringify(partiallyBroken), storage);
  assert.equal(result.success, false);
  assert.equal(storage.getItem(STORAGE_KEYS.PREFERENCES), existingPrefs);
  assert.equal(storage.getItem(STORAGE_KEYS.TASKS), existingTasks);
  assert.equal(storage.getItem(STORAGE_KEYS.HABIT), null);
});

test('importBackupToStorage restores valid v2 backup and rolls back on write error', () => {
  const initialPrefs = JSON.stringify({
    userName: 'BeforeBackup',
    hasCompletedOnboarding: true,
    showPrayerTimes: true,
  });
  const storage = createMemoryStorage({
    [STORAGE_KEYS.PREFERENCES]: initialPrefs,
  });

  const valid = createValidV2Backup();
  const okResult = importBackupToStorage(JSON.stringify(valid), storage);
  assert.equal(okResult.success, true);
  assert.equal(JSON.parse(storage.getItem(STORAGE_KEYS.PREFERENCES)!).userName, 'Alex');
  assert.equal(JSON.parse(storage.getItem(STORAGE_KEYS.HABIT)!).habitName, 'Late Night Scrolling');

  // Now simulate QuotaExceededError on the 3rd write and verify rollback restores 'Alex' (and not partial new data)
  let writeCount = 0;
  const failingStorage: StorageLike = {
    getItem: (k) => storage.getItem(k),
    removeItem: (k) => storage.removeItem(k),
    setItem: (k, v) => {
      writeCount += 1;
      if (writeCount === 3) {
        throw new Error('QuotaExceededError');
      }
      storage.setItem(k, v);
    },
  };

  const nextBackup = createValidV2Backup();
  nextBackup.preferences!.userName = 'HalfWritten';
  nextBackup.habit.habitName = 'HalfWrittenHabit';

  const failResult = importBackupToStorage(JSON.stringify(nextBackup), failingStorage);
  assert.equal(failResult.success, false);
  if (!failResult.success) {
    assert.match(failResult.error, /Existing data was left unchanged/);
  }
  assert.equal(JSON.parse(storage.getItem(STORAGE_KEYS.PREFERENCES)!).userName, 'Alex');
  assert.equal(JSON.parse(storage.getItem(STORAGE_KEYS.HABIT)!).habitName, 'Late Night Scrolling');
});
