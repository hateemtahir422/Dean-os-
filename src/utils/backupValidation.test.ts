// 2. Malformed JSON & File Limits
// ---------------------------------------------------------------------------

test('rejects empty string, whitespace, and broken JSON syntax', () => {
  for (const badInput of ['', '   ', '{ "version": 2, ', 'not json at all']) {
    const res = validateBackupJson(badInput);
    assert.equal(res.ok, false);
    if (!res.ok) {
      assert.ok(res.error.length > 0);
    }
  }
});

test('rejects non-object JSON roots (array, null, primitive)', () => {
  for (const raw of ['[]', 'null', '"hello"', '123', 'true']) {
    const res = validateBackupJson(raw);
    assert.equal(res.ok, false);
    if (!res.ok) {
      assert.match(res.error, /top-level JSON value must be an object/i);
    }
  }
});

test('rejects oversized backup payloads above MAX_BACKUP_BYTES', () => {
  const oversized = 'x'.repeat(MAX_BACKUP_BYTES + 10);
  const res = validateBackupJson(oversized);
  assert.equal(res.ok, false);
  if (!res.ok) {
    assert.match(res.error, /5 MB safety limit/i);
  }
});

